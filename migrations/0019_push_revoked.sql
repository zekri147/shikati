-- حذف الإشعارات من الإدارة (10/11/2026، بطلب ZEKRI): مثل حذف البصمة.
-- الهاتف يؤكد اشتراكه عند كل فتح (syncPush)، فلو حُذف الاشتراك وحده لعاد في الفتح التالي.
-- هنا عناوين الاشتراكات التي حذفها المدير: التأكيد التلقائي لا يعيدها، بل يلغي الهاتف اشتراكه.
-- التفعيل الصريح من «إشعارات الهاتف» يحذف العنوان من هنا ويشترك من جديد.
CREATE TABLE push_revoked (
  endpoint TEXT PRIMARY KEY,
  user_id  INTEGER,
  at       TEXT NOT NULL DEFAULT (datetime('now'))
);
